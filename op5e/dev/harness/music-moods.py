# Sorts songs into moods from audio features (tempo, loudness, onset density, brightness, minor feel) plus title cues. Ignores the playlist/folder a song is in.
# Inputs live in Foundry/actors-json (gitignored): music-features.json, music-vocals.json, playlists-dump.json. Output: op5e/docs/MUSIC-MOODS.md (review table).
import json, os, re
J = "../Foundry/actors-json/"
feat = json.load(open(J + "music-features.json", encoding="utf8"))
vox = {r["file"]: r for r in json.load(open(J + "music-vocals.json", encoding="utf8"))}
dump = json.load(open(J + "playlists-dump.json", encoding="utf8"))
dm = json.load(open(J + "music-demucs.json", encoding="utf8"))

# Songs that are actor themes (players + Meridian Island), kept out of the mood sort
THEME_PLAYLISTS = {"B.O.B", "Baptiste", "Jack", "Roma", "Tigor"}
theme = {}
for p in dump:
    if p["playlist"] in THEME_PLAYLISTS:
        for s in p["sounds"]: theme[s["path"].split("music/", 1)[-1]] = p["playlist"]
for rel in feat:
    if rel.startswith("Characters/Arancio/"): theme[rel] = "The Gallows"
    if rel.startswith("Characters/Armano/"): theme[rel] = "Kanto"

# Songs with sung lyrics (sure) or possibly (check): kept out of the moods, pending the user's review in MUSIC-VOCALS.md
SURE = ["Hoist the Colours", "Stabat Mater", "O Fortuna", "Phantom Of The Opera", "Me and the Devil", "Fenris Wolfblood", "medieval-chant", "An Toll Dubh", "Ace of Spades"]
CHECK = ["Vegeta", "Final Flash", "Full-Force Kamehameha", "Wandenreich", "Elden Ring Main Theme", "Blood Rose", "Hells Bells"]
def vocal_class(rel):
    n = rel
    if any(s in n for s in SURE): return "sure"
    if any(s in n for s in CHECK): return "check"
    return None

def pct(vals, p): xs = sorted(vals); return xs[int(p * (len(xs) - 1))]
F = {k: v for k, v in feat.items() if "tempo" in v}
on33, on66 = pct([v["onset"] for v in F.values()], .33), pct([v["onset"] for v in F.values()], .66)
ld33, ld66 = pct([v["loud_db"] for v in F.values()], .33), pct([v["loud_db"] for v in F.values()], .66)
ct33, ct66 = pct([v["centroid"] for v in F.values()], .33), pct([v["centroid"] for v in F.values()], .66)
def energy(v):  # 0..1 blend of onset density, loudness and brightness (each ranked against the library)
    def r(x, lo, hi): return max(0.0, min(1.0, (x - lo) / (hi - lo))) if hi > lo else 0.5
    return 0.5 * r(v["onset"], on33 * 0.9, on66 * 1.25) + 0.3 * r(v["loud_db"], ld33 - 3, ld66 + 3) + 0.2 * r(v["centroid"], ct33 * 0.8, ct66 * 1.2)

KEY = [
  ("Combat", r"battle|fight|strike|attack|combat|frenzy|war |bankai|vs |versus|raid|siege|duel|slayer|kamehameha|final flash|rage|wrath"),
  ("Epic", r"boss|king|theme|legend|triumph|glory|rise|awakening|evolves|supreme|crown|conquer|throne|hero"),
  ("Tension", r"dread|shadow|belly|vessel|abyss|dark|hunt|stalk|silent|fear|cold|undead|beast|blight|serpent|crypt|doom|sinister|cyborg|horror"),
  ("Travel", r"journey|trail|voyage|sailing|path|road|travel|explor|wander|adventure|march|horizon|pirate|sea|ship|wind"),
  ("Calm", r"calm|peace|rest|lullaby|dawn|morning|village|tavern|camp|serene|gentle|quiet|home|garden"),
  ("Sad", r"requiem|lacrimosa|sad|tear|lament|farewell|grief|memory|memories|loss|goodbye|sorrow|elegy"),
]
def name_of(rel): return os.path.splitext(os.path.basename(rel))[0].replace("_spotdown.org", "").lower()
def mood(rel, v):
    n = name_of(rel); e = energy(v); minor = v["minor"]; t = v["tempo"]
    hit = next((m for m, rx in KEY if re.search(rx, n)), None)
    if hit and e > 0.55 and hit in ("Calm", "Sad"): hit = None   # a quiet word in a loud song does not make it calm
    if hit and e < 0.30 and hit in ("Combat", "Epic"): hit = None
    if hit: return hit, f"title cue + energy {e:.2f}"
    if e >= 0.62: return ("Combat", f"energy {e:.2f}, tempo {t}") if t >= 118 else ("Epic", f"energy {e:.2f}, slower ({t} bpm)")
    if e >= 0.42: return ("Tension", f"mid energy {e:.2f}, minor {minor:+.2f}") if minor > 0.10 else ("Travel", f"mid energy {e:.2f}, tempo {t}")
    if minor > 0.10: return "Sad" if e < 0.30 else "Tension", f"low energy {e:.2f}, minor {minor:+.2f}"
    return "Calm", f"low energy {e:.2f}, tempo {t}"

rows = []
for rel, v in F.items():
    if rel in theme: continue
    vc = vocal_class(rel)
    m, why = ("Vocal", f"lyrics {vc}") if vc else mood(rel, v)
    rows.append((m, energy(v), rel, why, v, dm.get(rel, {}).get("frac_gt_025")))
order = ["Combat", "Epic", "Tension", "Travel", "Calm", "Sad", "Vocal"]
out = ["# Music mood sort", "",
       "Draft for review (2026-10-11). Songs are sorted by what they sound like (tempo, energy, brightness, major or minor feel) with title cues; **the playlist or folder a song is currently in is ignored.** Generated by `op5e/dev/harness/music-moods.py`; correct the last column and I rebuild.", "",
       f"Actor themes are kept out of this sort (players and Meridian Island only, see [MUSIC-THEMES.md](MUSIC-THEMES.md)): {len(theme)} songs. Vocal songs (sung lyrics) wait in their own group.", ""]
for m in order:
    g = sorted((r for r in rows if r[0] == m), key=lambda r: -r[1])
    out += [f"## {m} ({len(g)})", "", "| Song | Why | Voice score | Mood? (you) |", "|---|---|---|---|"]
    for _, e, rel, why, v, vs in g:
        out.append(f"| {rel.replace('|', '/')} | {why} | {'' if vs is None else f'{vs:.2f}'} | |")
    out.append("")
out += ["## Actor themes (not sorted)", "", "| Song | Actor |", "|---|---|"] + [f"| {k} | {a} |" for k, a in sorted(theme.items(), key=lambda x: x[1])]
open("docs/MUSIC-MOODS.md", "w", encoding="utf8").write("\n".join(out) + "\n")
from collections import Counter; print(Counter(r[0] for r in rows), "themes", len(theme))
