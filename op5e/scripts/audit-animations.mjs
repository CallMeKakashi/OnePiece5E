// Usage: node scripts/audit-animations.mjs [--packs <packs-src>] [--autorec <autorec.json>]
// Writes reports/animation-coverage.{json,md}. "after" counts also use assets/autorec-op5e.json when present.
import { writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { AA_MENUS, buildLabelIndex, matchAutorec, isCoveredByModule, describeDoc, rinse } from "./animations-lib.mjs";
import { ROOT, parseArgs, loadDocs, readJson } from "./animations-tools.mjs";

const args = parseArgs();
const autorec = readJson(args.autorec);
const ours = existsSync(join(ROOT, "assets/autorec-op5e.json")) ? readJson(join(ROOT, "assets/autorec-op5e.json")) : {};
const oursLabels = new Set(AA_MENUS.flatMap((m) => (ours[m] ?? []).map((e) => rinse(e.label))));
const index = buildLabelIndex(autorec);

const rows = [];
let totalDocs = 0;
for (const doc of loadDocs(args.packs)) {
  totalDocs++;
  const d = describeDoc(doc);
  if (!d) continue;
  const m = matchAutorec(index, doc.name);
  rows.push({
    name: doc.name,
    pack: doc._pack,
    activityTypes: d.activityTypes,
    damageType: d.damageType || null,
    school: d.school || null,
    shape: d.shape || null,
    nameMatch: m?.kind ?? "none",
    matchedLabel: m?.label ?? null,
    coveredByModule: isCoveredByModule(index, doc.name),
    coveredByOp5e: oursLabels.has(rinse(doc.name)),
  });
}
for (const r of rows) r.covered = r.coveredByModule || r.coveredByOp5e;

const tally = (rs, key) => {
  const t = { docs: rs.length, exactNameBefore: 0, moduleBefore: 0, after: 0 };
  for (const r of rs) {
    if (r.nameMatch === "exact") t.exactNameBefore++;
    if (r.coveredByModule) t.moduleBefore++;
    if (r.covered) t.after++;
  }
  return key ? { [key]: t } : t;
};
const groupBy = (keyFn) => {
  const g = {};
  for (const r of rows) for (const k of [].concat(keyFn(r))) (g[k ?? "(none)"] ??= []).push(r);
  return Object.fromEntries(Object.entries(g).sort().map(([k, v]) => [k, tally(v)]));
};

const report = {
  generated: new Date().toISOString(),
  autorecSource: args.autorec,
  totalDocsScanned: totalDocs,
  summary: tally(rows),
  byPack: groupBy((r) => r.pack),
  byActivityType: groupBy((r) => r.activityTypes),
  byDamageType: groupBy((r) => r.damageType),
  bySchool: groupBy((r) => r.school),
  uncoveredAfter: rows.filter((r) => !r.covered).map((r) => ({ name: r.name, pack: r.pack, activityTypes: r.activityTypes })),
  docs: rows,
};
writeFileSync(join(ROOT, "reports/animation-coverage.json"), JSON.stringify(report, null, 2) + "\n");

const table = (title, g) =>
  `## ${title}\n\n| group | docs | exact name (before) | module match (before) | after |\n|---|---:|---:|---:|---:|\n` +
  Object.entries(g).map(([k, t]) => `| ${k} | ${t.docs} | ${t.exactNameBefore} | ${t.moduleBefore} | ${t.after} |`).join("\n") + "\n";
const s = report.summary;
const md = [
  "# Animation coverage (attack / save / damage / heal / summon / template docs)",
  "",
  `Generated by \`scripts/audit-animations.mjs\`. Docs scanned: ${totalDocs}; docs with an animatable activity: ${s.docs}.`,
  "",
  `- Exact autorec name match (issue #29 measure): **${s.exactNameBefore}/${s.docs}**`,
  `- Covered by dnd5e-animations (AA substring semantics): **${s.moduleBefore}/${s.docs}**`,
  `- Covered after op5e autorec entries: **${s.after}/${s.docs}**`,
  `- Still uncovered: ${report.uncoveredAfter.length}`,
  "",
  table("By pack", report.byPack),
  table("By activity type", report.byActivityType),
  table("By damage type", report.byDamageType),
  table("By spell school", report.bySchool),
].join("\n");
writeFileSync(join(ROOT, "reports/animation-coverage.md"), md);
console.log(JSON.stringify(report.summary), "uncovered:", report.uncoveredAfter.length);
